  const TABLE = {en: {}, ko: {}};
  const PATTERNS = {en: [], ko: []};
  for (const [source, [en, ko]] of Object.entries(M)) {
    for (const [lang, text] of [['en', en], ['ko', ko]]) {
      if (!/\{\d\}/.test(source)) { TABLE[lang][source] = text; continue; }
      const names = [];
      const regex = new RegExp('^' + source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{(\d)\\\}/g, (_, n) => { names.push(Number(n)); return '([\\s\\S]+?)'; }) + '$');
      PATTERNS[lang].push({regex, names, text, weight: source.replace(/\{\d\}/g, '').length});
    }
  }
  for (const lang of ['en', 'ko']) PATTERNS[lang].sort((a, b) => b.weight - a.weight);

  const CJK = /[㐀-鿿]/;
  function normalize(value) {
    const text = String(value || '').toLowerCase();
    if (text.startsWith('ko')) return 'ko';
    if (text.startsWith('zh')) return 'zh-CN';
    if (text.startsWith('en')) return 'en';
    return '';
  }
  function translate(text, lang, depth = 0, context = '') {
    if (text == null) return text;
    text = String(text);
    if (!TABLE[lang] || !CJK.test(text) || depth > 4) return text;
    const lead = text.match(/^\s*/)[0], trail = text.slice(lead.length).match(/\s*$/)[0];
    const core = text.slice(lead.length, text.length - trail.length);
    let out = context && TABLE[lang][core + '#' + context] || TABLE[lang][core];
    if (out == null) {
      for (const pattern of PATTERNS[lang]) {
        const match = core.match(pattern.regex);
        if (!match) continue;
        out = pattern.text.replace(/\{(\d)\}/g, (_, n) => translate(match[pattern.names.indexOf(Number(n)) + 1], lang, depth + 1));
        break;
      }
    }
    // Segments joined with " · " are translated one by one (e.g. "Top · 51% win rate").
    if (out == null && core.includes('·')) {
      const parts = core.split(/(\s*·\s*)/).map((part, index) => index % 2 ? part : translate(part, lang, depth + 1));
      if (parts.join('') !== core) out = parts.join('');
    }
    return out == null ? text : lead + out + trail;
  }
  return {LANGUAGES, INTL, normalize, translate, CJK};
